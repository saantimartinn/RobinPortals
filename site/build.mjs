// Builds the shared Robin site: one function wrapper per app function (named
// with the app prefix) and every app frontend under its own path.
// Usage: node site/build.mjs [--install] [--watch]
//   --install  run `npm ci` for each app package (used by the Netlify build)
//   --watch    rebuild frontends on change and write Lambda-compatible function
//              wrappers (used by local development)
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { APPS, ROOT, PUBLIC_DIR, FUNCTIONS_DIR, functionName } from './apps.mjs';
import { buildConfig, renderConfig } from './generate-config.mjs';

const install = process.argv.includes('--install');
const watch = process.argv.includes('--watch');

function run(command, args, cwd, env = process.env) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit', env });
  if (result.status !== 0) {
    console.error(`[site] ${command} ${args.join(' ')} failed in ${relative(ROOT, cwd) || '.'}`);
    process.exit(result.status || 1);
  }
}

function checkConfig() {
  const current = existsSync(resolve(ROOT, 'netlify.toml')) ? readFileSync(resolve(ROOT, 'netlify.toml'), 'utf8') : '';
  if (current !== renderConfig(buildConfig().config)) {
    console.error('[site] netlify.toml is out of date; run `npm run site:config` and commit it.');
    process.exit(1);
  }
}

function installDependencies() {
  const packages = new Set();
  for (const app of APPS) {
    packages.add(app.dir);
    if (existsSync(resolve(ROOT, app.frontend, 'package-lock.json'))) packages.add(app.frontend);
  }
  for (const dir of packages) {
    if (existsSync(resolve(ROOT, dir, 'package-lock.json'))) run('npm', ['ci', '--include=dev'], resolve(ROOT, dir));
  }
}

function writeFunctionWrappers() {
  const scheduled = new Set(Object.entries(buildConfig().config.functions).filter(([, settings]) => settings?.schedule).map(([name]) => name));
  rmSync(FUNCTIONS_DIR, { recursive: true, force: true });
  mkdirSync(FUNCTIONS_DIR, { recursive: true });
  let count = 0;
  for (const app of APPS) {
    const source = resolve(ROOT, app.dir, app.functions);
    for (const file of readdirSync(source).filter((name) => name.endsWith('.js'))) {
      const target = relative(FUNCTIONS_DIR, resolve(source, file));
      const runtime = relative(FUNCTIONS_DIR, resolve(ROOT, 'site/app-env.cjs'));
      const name = functionName(app, file.slice(0, -3));
      const header = [
        `// Generated by site/build.mjs; the function lives in ${relative(ROOT, resolve(source, file))}`,
        `// and runs with the ${app.id} environment (see site/app-env.cjs).`,
      ];
      if (watch) {
        // Locally, a Lambda-compatible function: `netlify dev` runs it in place, while modern
        // functions are each traced first, and 254 of them exceed macOS's open-file limit.
        writeFileSync(resolve(FUNCTIONS_DIR, `${name}.js`), [
          ...header,
          `module.exports = require(${JSON.stringify(runtime)}).${scheduled.has(name) ? 'wrapScheduled' : 'wrapFunction'}(${JSON.stringify(app.id)}, () => require(${JSON.stringify(target)}));`,
          '',
        ].join('\n'));
      } else {
        // On Netlify, a modern function (see serve in site/app-env.cjs): Lambda compatibility
        // mode caps the environment at 4 KB. It is ESM so Netlify bundles it as is: a CommonJS
        // wrapper gets transpiled and moved, and the bundle then misses the app's node_modules.
        writeFileSync(resolve(FUNCTIONS_DIR, `${name}.mjs`), [
          ...header,
          `import { createRequire } from 'node:module';`,
          `import runtime from ${JSON.stringify(runtime)};`,
          `const require = createRequire(import.meta.url);`,
          `export default runtime.serve(${JSON.stringify(app.id)}, () => require(${JSON.stringify(target)}), { scheduled: ${scheduled.has(name)} });`,
          '',
        ].join('\n'));
      }
      count += 1;
    }
  }
  console.log(`[site] ${count} functions written to ${relative(ROOT, FUNCTIONS_DIR)}`);
}

// Vite reads VITE_* from the app's .env locally; on Netlify they arrive as APP__VITE_*.
function viteEnv(app) {
  const prefix = `${app.id.toUpperCase()}__`;
  const vite = Object.fromEntries(Object.entries(process.env)
    .filter(([key]) => key.startsWith(`${prefix}VITE_`))
    .map(([key, value]) => [key.slice(prefix.length), value]));
  return { ...process.env, ...vite };
}

function viteArgs(app) {
  const outDir = resolve(PUBLIC_DIR, app.uiPath.slice(1));
  return ['--no-install', 'vite', 'build', '--outDir', outDir, '--emptyOutDir', ...(watch ? ['--watch'] : [])];
}

checkConfig();
if (install) installDependencies();
writeFunctionWrappers();
mkdirSync(PUBLIC_DIR, { recursive: true });

if (watch) {
  const children = APPS.map((app) => {
    const child = spawn('npx', viteArgs(app), { cwd: resolve(ROOT, app.frontend), stdio: ['ignore', 'pipe', 'pipe'], env: viteEnv(app) });
    for (const stream of [child.stdout, child.stderr]) {
      stream.on('data', (chunk) => {
        for (const line of chunk.toString().split(/\r?\n/).filter(Boolean)) console.log(`[${app.id}] ${line}`);
      });
    }
    return child;
  });
  const stop = () => children.forEach((child) => child.kill('SIGTERM'));
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
} else {
  for (const app of APPS) {
    console.log(`[site] building ${app.id} -> ${app.uiPath}/`);
    run('npx', viteArgs(app), resolve(ROOT, app.frontend), viteEnv(app));
  }
  console.log(`[site] done: ${relative(ROOT, PUBLIC_DIR)}`);
}
