// Generates the root netlify.toml for the shared Robin site from each app's
// netlify.toml: API redirects are remounted under the app's path, functions are
// renamed with the app prefix, and headers are scoped to the app's paths.
// Usage: node site/generate-config.mjs [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse, stringify } from 'smol-toml';
import { APPS, ROOT, PUBLIC_DIR, FUNCTIONS_DIR, EDGE_FUNCTIONS_DIR, functionName } from './apps.mjs';

const FUNCTION_TARGET = /^\/\.netlify\/functions\/([^/?]+)(.*)$/;

function functionNames(app) {
  return new Set(readdirSync(resolve(ROOT, app.dir, app.functions))
    .filter((file) => file.endsWith('.js'))
    .map((file) => file.slice(0, -3)));
}

function remountRedirect(app, redirect, names) {
  const match = redirect.to.match(FUNCTION_TARGET);
  if (!match) return null;
  const [, name, rest] = match;
  if (!names.has(name)) throw new Error(`${app.id}: redirect ${redirect.from} points at missing function ${name}`);
  return { ...redirect, from: app.apiPath + redirect.from, to: `/.netlify/functions/${functionName(app, name)}${rest}` };
}

// Maps a header path from the app's standalone site to its path on the shared site.
function remountHeaderPath(app, path) {
  if (path === '/.netlify/functions/*') return path;
  if (path === '/*') return `${app.uiPath}/*`;
  if (path.startsWith('/api/')) return app.apiPath + path;
  if (app.legacyUiPath && (path === app.legacyUiPath || path.startsWith(`${app.legacyUiPath}/`))) {
    return app.uiPath + path.slice(app.legacyUiPath.length);
  }
  return app.uiPath + path;
}

function uiRoutes() {
  const routes = [
    // Only reached when the apps site is opened directly; the public website owns "/".
    { from: '/', to: '/portal/', status: 302 },
    // The common login is the student portal.
    { from: '/login', to: '/portal/index.html', status: 200 },
    { from: '/login/', to: '/portal/index.html', status: 200 },
  ];
  for (const app of APPS) {
    routes.push(app.id === 'admin'
      ? { from: app.uiPath, to: `${app.uiPath}/index.html`, status: 200 }
      : { from: app.uiPath, to: `${app.uiPath}/`, status: 301 });
    routes.push({ from: `${app.uiPath}/*`, to: `${app.uiPath}/index.html`, status: 200 });
  }
  return routes;
}

export function buildConfig() {
  const redirects = [];
  const headers = [];
  const functions = { directory: relative(ROOT, FUNCTIONS_DIR) };
  const dropped = [];

  for (const app of APPS) {
    const config = parse(readFileSync(resolve(ROOT, app.dir, 'netlify.toml'), 'utf8'));
    const names = functionNames(app);

    for (const redirect of [...(config.redirects || []), ...(app.extraRedirects || [])]) {
      const remounted = remountRedirect(app, redirect, names);
      if (remounted) redirects.push(remounted);
      else if (redirect.from.startsWith('/api/')) throw new Error(`${app.id}: unexpected non-function API redirect ${redirect.from}`);
      else dropped.push(`${app.id}: ${redirect.from} -> ${redirect.to}`);
    }

    for (const header of config.headers || []) {
      const path = remountHeaderPath(app, header.for);
      if (headers.some((existing) => existing.for === path)) {
        const existing = headers.find((item) => item.for === path);
        if (JSON.stringify(existing.values) !== JSON.stringify(header.values)) {
          throw new Error(`${app.id}: conflicting headers for ${path}`);
        }
        continue;
      }
      headers.push({ for: path, values: header.values });
      if (app.id === 'portal' && header.for === '/*') {
        headers.push({ for: '/login', values: header.values }, { for: '/login/', values: header.values });
      }
      if (app.id === 'admin' && header.for === '/*') headers.push({ for: app.uiPath, values: header.values });
    }

    const { node_bundler: bundler, ...rest } = config.functions || {};
    const perFunction = Object.fromEntries(Object.entries(rest).filter(([, value]) => typeof value === 'object'));
    for (const [name, settings] of Object.entries(perFunction)) {
      if (!names.has(name)) throw new Error(`${app.id}: settings for missing function ${name}`);
      functions[functionName(app, name)] = settings;
    }
    if (bundler || app.bundler) functions[`${app.id}-*`] = { node_bundler: bundler || app.bundler };
  }

  redirects.push(...uiRoutes());

  const config = {
    build: {
      command: 'node site/build.mjs --install',
      publish: relative(ROOT, PUBLIC_DIR),
      edge_functions: relative(ROOT, EDGE_FUNCTIONS_DIR),
      environment: { NODE_VERSION: '22' },
    },
    dev: { framework: '#static', port: 8889, autoLaunch: false },
    functions,
    redirects,
    headers,
  };
  return { config, dropped };
}

export function renderConfig(config) {
  return [
    '# Generated by site/generate-config.mjs from apps/*/netlify.toml. Do not edit by hand:',
    '# change the app\'s own netlify.toml (or site/apps.mjs) and run `npm run site:config`.',
    '',
    stringify(config),
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { config, dropped } = buildConfig();
  const output = resolve(ROOT, 'netlify.toml');
  const rendered = renderConfig(config);
  if (process.argv.includes('--check')) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== rendered) {
      console.error('netlify.toml is out of date; run `npm run site:config`.');
      process.exit(1);
    }
    console.log('netlify.toml is up to date.');
  } else {
    writeFileSync(output, rendered);
    const functionCount = APPS.reduce((total, app) => total + functionNames(app).size, 0);
    console.log(`netlify.toml: ${config.redirects.length} redirects, ${config.headers.length} header rules, ${functionCount} functions.`);
    console.log('Standalone-site redirects replaced by the shared routes:');
    for (const line of dropped) console.log(`  ${line}`);
  }
}
